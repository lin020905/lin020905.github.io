const storageKey = "lin020905-site-language";
const languageButtons = document.querySelectorAll("[data-language]");
const translatableNodes = document.querySelectorAll("[data-i18n]");
const metaDescription = document.querySelector('meta[name="description"]');
const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const hasFinePointer = window.matchMedia("(pointer: fine)").matches;

function readSavedLanguage() {
  try {
    return localStorage.getItem(storageKey);
  } catch {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    return;
  }
}

function getInitialLanguage() {
  const savedLanguage = readSavedLanguage();
  return savedLanguage === "en" || savedLanguage === "zh" ? savedLanguage : "zh";
}

function animateLanguageChange() {
  if (prefersReducedMotion.matches) {
    return;
  }

  document.body.classList.remove("is-language-changing");
  void document.body.offsetWidth;
  document.body.classList.add("is-language-changing");

  window.setTimeout(() => {
    document.body.classList.remove("is-language-changing");
  }, 260);
}

function setLanguage(language) {
  const dictionary = translations[language] || translations.zh;

  translatableNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.setAttribute("aria-pressed", String(isActive));
  });

  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.documentElement.dataset.language = language;
  document.title = dictionary.documentTitle;

  if (metaDescription) {
    metaDescription.setAttribute("content", dictionary.documentDescription);
  }

  saveLanguage(language);
  animateLanguageChange();
}

function setupLanguageSwitch() {
  languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.language);
    });
  });

  setLanguage(getInitialLanguage());
}

function setupReveal() {
  const revealNodes = document.querySelectorAll("[data-reveal]");

  if (!revealNodes.length) {
    return;
  }

  document.documentElement.classList.add("reveal-ready");

  if (!("IntersectionObserver" in window) || prefersReducedMotion.matches) {
    revealNodes.forEach((node) => node.classList.add("is-visible"));
    return;
  }

  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    {
      rootMargin: "0px 0px -70px 0px",
      threshold: 0.12,
    },
  );

  revealNodes.forEach((node) => revealObserver.observe(node));
}

function setupPointerField() {
  if (!hasFinePointer || prefersReducedMotion.matches) {
    return;
  }

  let latestPointer = null;
  let animationFrame = null;

  window.addEventListener("pointermove", (event) => {
    latestPointer = event;

    if (animationFrame) {
      return;
    }

    animationFrame = window.requestAnimationFrame(() => {
      document.body.style.setProperty("--cursor-x", `${latestPointer.clientX}px`);
      document.body.style.setProperty("--cursor-y", `${latestPointer.clientY}px`);
      document.body.classList.add("is-pointer-active");
      animationFrame = null;
    });
  });

  window.addEventListener("pointerleave", () => {
    document.body.classList.remove("is-pointer-active");
  });
}

function setupTiltCards() {
  const tiltCards = document.querySelectorAll("[data-tilt]");

  if (!tiltCards.length || !hasFinePointer || prefersReducedMotion.matches) {
    return;
  }

  tiltCards.forEach((card) => {
    card.addEventListener("pointermove", (event) => {
      const rect = card.getBoundingClientRect();
      const relativeX = (event.clientX - rect.left) / rect.width - 0.5;
      const relativeY = (event.clientY - rect.top) / rect.height - 0.5;

      card.style.setProperty("--tilt-x", `${relativeY * -5}deg`);
      card.style.setProperty("--tilt-y", `${relativeX * 5}deg`);
    });

    card.addEventListener("pointerleave", () => {
      card.style.setProperty("--tilt-x", "0deg");
      card.style.setProperty("--tilt-y", "0deg");
    });
  });
}

setupLanguageSwitch();
setupReveal();
setupPointerField();
setupTiltCards();
